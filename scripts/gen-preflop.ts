/**
 * Generates src/ai/preflopRanking.ts: the 169 starting-hand classes ordered
 * by strength (equity vs 1 and vs 3 random hands, each relative to the fair
 * share). Run once with: bun scripts/gen-preflop.ts
 */
import { writeFileSync } from 'node:fs';
import { RANKS, makeCard } from '../src/engine/cards';
import { monteCarloEquity } from '../src/ai/equity';
import { seedRng } from '../src/engine/rng';

const classes: { name: string; cards: [number, number]; combos: number }[] = [];
for (let hi = 12; hi >= 0; hi--)
  for (let lo = hi; lo >= 0; lo--) {
    if (hi === lo) classes.push({ name: RANKS[hi] + RANKS[lo], cards: [makeCard(hi, 0), makeCard(lo, 1)], combos: 6 });
    else {
      classes.push({ name: RANKS[hi] + RANKS[lo] + 's', cards: [makeCard(hi, 0), makeCard(lo, 0)], combos: 4 });
      classes.push({ name: RANKS[hi] + RANKS[lo] + 'o', cards: [makeCard(hi, 0), makeCard(lo, 1)], combos: 12 });
    }
  }
const rng = seedRng(20261108);
const scored = classes.map((c) => {
  const e1 = monteCarloEquity({ hero: c.cards, board: [], opponentMinChen: [-10], iterations: 40000 }, rng);
  const e3 = monteCarloEquity({ hero: c.cards, board: [], opponentMinChen: [-10, -10, -10], iterations: 40000 }, rng);
  return { ...c, e1, e3, score: e1 / 0.5 + e3 / 0.25 };
});
scored.sort((a, b) => b.score - a.score);
const out = `// Generated by scripts/gen-preflop.ts – do not edit by hand.
/** The 169 starting-hand classes from strongest to weakest. */
export const PREFLOP_ORDER = ${JSON.stringify(scored.map((s) => s.name))};
/** Heads-up equity vs a random hand, same order. */
export const PREFLOP_EQUITY_HU = ${JSON.stringify(scored.map((s) => +s.e1.toFixed(4)))};
`;
writeFileSync('src/ai/preflopRanking.ts', out);
